function x = tent_sequence(n, seed)
%TENT_SEQUENCE 生成长度 n 的 Tent 混沌序列，取值位于 (0,1)。
%
% 对落入短周期或精确边界的值加入极小扰动，避免 {0,1,0,...} 等退化序列。

% [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
if nargin < 2 || isempty(seed)
    % [逐行说明] 计算或更新 `seed`，供后续算法、评价或日志步骤使用。
    seed = rand;
end
% [逐行说明] 计算或更新 `x`，供后续算法、评价或日志步骤使用。
x = zeros(1, n);
% [逐行说明] 计算或更新 `x(1)`，供后续算法、评价或日志步骤使用。
x(1) = min(max(seed, eps), 1-eps);
% [逐行说明] 开始按给定索引范围逐项执行循环。
for i = 2:n
    % [逐行说明] 计算或更新 `prev`，供后续算法、评价或日志步骤使用。
    prev = x(i-1);
    % [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
    if prev < 0.5
        % [逐行说明] 计算或更新 `next`，供后续算法、评价或日志步骤使用。
        next = 2 * prev;
    % [逐行说明] 处理前述条件均不成立的情况。
    else
        % [逐行说明] 计算或更新 `next`，供后续算法、评价或日志步骤使用。
        next = 2 * (1 - prev);
    end
    % [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
    if next <= eps || next >= 1-eps || any(abs(next - [0.25 0.5 0.7 0.75]) < 1e-12)
        % [逐行说明] 计算或更新 `next`，供后续算法、评价或日志步骤使用。
        next = mod(next + 0.1 * rand, 1);
    end
    % [逐行说明] 计算或更新 `x(i)`，供后续算法、评价或日志步骤使用。
    x(i) = min(max(next, eps), 1-eps);
end
end
