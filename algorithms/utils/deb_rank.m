function order = deb_rank(results)
%DEB_RANK 按 Deb 规则从好到坏排列结果结构体/元胞数组。
%
% 为避免 O(N^2) 逐对比较，这里构造稳定的词典序键：
%   可行个体键 = [0, 0, F]
%   不可行个体键 = [1, CV, F]

% [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
if iscell(results)
    % [逐行说明] 计算或更新 `n`，供后续算法、评价或日志步骤使用。
    n = numel(results);
    % [逐行说明] 计算或更新 `getr`，供后续算法、评价或日志步骤使用。
    getr = @(i) results{i};
% [逐行说明] 处理前述条件均不成立的情况。
else
    % [逐行说明] 计算或更新 `n`，供后续算法、评价或日志步骤使用。
    n = numel(results);
    % [逐行说明] 计算或更新 `getr`，供后续算法、评价或日志步骤使用。
    getr = @(i) results(i);
end
% [逐行说明] 计算或更新 `keys`，供后续算法、评价或日志步骤使用。
keys = zeros(n, 4);
% [逐行说明] 开始按给定索引范围逐项执行循环。
for i = 1:n
    % [逐行说明] 计算或更新 `r`，供后续算法、评价或日志步骤使用。
    r = getr(i);
    % [逐行说明] 计算或更新 `keys(i,1)`，供后续算法、评价或日志步骤使用。
    keys(i,1) = ~r.isFeasible;
    % [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
    if r.isFeasible
        % [逐行说明] 计算或更新 `keys(i,2)`，供后续算法、评价或日志步骤使用。
        keys(i,2) = 0;
    % [逐行说明] 处理前述条件均不成立的情况。
    else
        % [逐行说明] 计算或更新 `keys(i,2)`，供后续算法、评价或日志步骤使用。
        keys(i,2) = r.CV;
    end
    % [逐行说明] 计算或更新 `keys(i,3)`，供后续算法、评价或日志步骤使用。
    keys(i,3) = r.F;
    % [逐行说明] 计算或更新 `keys(i,4)`，供后续算法、评价或日志步骤使用。
    keys(i,4) = i; % 保证相同结果时顺序确定，增强复现性
end
% [逐行说明] 执行当前 MATLAB 语句，完成所在步骤规定的计算或状态更新。
[~, order] = sortrows(keys, [1 2 3 4]);
end
