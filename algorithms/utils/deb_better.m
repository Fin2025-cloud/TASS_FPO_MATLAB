function tf = deb_better(a, b, tol)
%DEB_BETTER 按 Deb 可行性规则判断结果 a 是否优于 b。
%
% 输入 a、b 至少需要字段：
%   isFeasible : 逻辑值
%   F          : 综合目标（越小越好）
%   CV         : 无量纲总违反度（越小越好）
%
% 规则：
%   1) 可行优于不可行；
%   2) 都可行时比较 F；
%   3) 都不可行时比较 CV，近似相等时再比较 F。

% [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
if nargin < 3 || isempty(tol)
    % [逐行说明] 计算或更新 `tol`，供后续算法、评价或日志步骤使用。
    tol = 1e-12;
end
% [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
if isempty(b)
    % [逐行说明] 计算或更新 `tf`，供后续算法、评价或日志步骤使用。
    tf = true;
    % [逐行说明] 结束当前函数并把已计算结果返回调用方。
    return;
end
% [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
if isempty(a)
    % [逐行说明] 计算或更新 `tf`，供后续算法、评价或日志步骤使用。
    tf = false;
    % [逐行说明] 结束当前函数并把已计算结果返回调用方。
    return;
end

% [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
if a.isFeasible && ~b.isFeasible
    % [逐行说明] 计算或更新 `tf`，供后续算法、评价或日志步骤使用。
    tf = true;
% [逐行说明] 在前一条件不成立时继续判断当前条件。
elseif ~a.isFeasible && b.isFeasible
    % [逐行说明] 计算或更新 `tf`，供后续算法、评价或日志步骤使用。
    tf = false;
% [逐行说明] 在前一条件不成立时继续判断当前条件。
elseif a.isFeasible && b.isFeasible
    % [逐行说明] 计算或更新 `tf`，供后续算法、评价或日志步骤使用。
    tf = a.F < b.F - tol;
% [逐行说明] 处理前述条件均不成立的情况。
else
    % [逐行说明] 判断当前条件是否成立，成立时执行对应分支。
    if a.CV < b.CV - tol
        % [逐行说明] 计算或更新 `tf`，供后续算法、评价或日志步骤使用。
        tf = true;
    % [逐行说明] 在前一条件不成立时继续判断当前条件。
    elseif abs(a.CV - b.CV) <= tol
        % [逐行说明] 计算或更新 `tf`，供后续算法、评价或日志步骤使用。
        tf = a.F < b.F - tol;
    % [逐行说明] 处理前述条件均不成立的情况。
    else
        % [逐行说明] 计算或更新 `tf`，供后续算法、评价或日志步骤使用。
        tf = false;
    end
end
end
